const CHAPTERS: Record<Lang, string[]> = {
  ru: ['Джунгли', 'Река', 'Водопад', 'Ночные джунгли', 'Затерянный храм', 'Мангры', 'Карнавал', 'Эльдорадо'],
  en: ['Jungle', 'River', 'Waterfall', 'Jungle Night', 'Lost Temple', 'Mangroves', 'Carnival', 'El Dorado'],
};

let lang: Lang = 'ru';

export function setLang(l: Lang): void {
  lang = l;
  document.documentElement.lang = l;
}

export function getLang(): Lang {
  return lang;
}

export function t(key: string, params: Record<string, string | number> = {}): string {
  const s = (lang === 'ru' ? ru : en)[key] ?? ru[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? ''));
}

export function chapterName(i: number): string {
  const list = CHAPTERS[lang];
  return list[i % list.length];
}
