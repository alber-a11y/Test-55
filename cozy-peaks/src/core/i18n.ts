const DICTS: Record<Lang, Dict> = { ru, en };

let lang: Lang = 'ru';
let gender: 'm' | 'f' = 'f';

export function setLang(l: Lang): void {
  lang = l;
  document.documentElement.lang = l;
}
export function getLang(): Lang {
  return lang;
}
export function setGender(g: 'm' | 'f'): void {
  gender = g;
}

export function t(key: string, params: Record<string, string | number> = {}): string {
  const e = DICTS[lang][key] ?? DICTS.ru[key] ?? key;
  let s = typeof e === 'string' ? e : e[gender];
  for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Text from data. */
export const tr = (l: L10n): string => l[lang];

export function detectLang(platformLang: Lang | null, saved: Lang | null): Lang {
  const q = new URLSearchParams(location.search).get('lang');
  if (q === 'ru' || q === 'en') return q;
  if (saved) return saved;
  if (platformLang) return platformLang;
  const nav = (navigator.language || 'ru').toLowerCase();
  return /^(ru|be|uk|kk|uz|ky|tg|hy|az|ka)/.test(nav) ? 'ru' : 'en';
}

export function formatTime(ms: number): string {
  const s = Math.ceil(ms / 1000);
  const m = Math.floor(s / 60);
  const h = Math.floor(m / 60);
  if (h > 0) return `${h}:${String(m % 60).padStart(2, '0')}:${String(s % 60).padStart(2, '0')}`;
  return `${m}:${String(s % 60).padStart(2, '0')}`;
}

export function formatNum(n: number): string {
  return n.toLocaleString(lang === 'ru' ? 'ru-RU' : 'en-US');
}
