const dicts: Record<Lang, Record<TKey, string>> = { ru, en };
let lang: Lang = 'ru';

export function detectLang(saved: Lang | null, platformLang: Lang | null): Lang {
  if (saved) return saved;
  if (platformLang) return platformLang;
  const q = new URLSearchParams(location.search).get('lang');
  if (q === 'ru' || q === 'en') return q;
  const nav = (navigator.language || 'ru').toLowerCase();
  return /^(ru|uk|be|kk|uz|ky|tg|hy|az|ka)/.test(nav) ? 'ru' : 'en';
}

export function setLang(l: Lang): void {
  lang = l;
  document.documentElement.lang = l;
  document.title = l === 'ru' ? 'Мастер Плиток: Три в ряд' : 'Tile Master: Match 3';
}

export function getLang(): Lang {
  return lang;
}

export function t(key: TKey, params?: Record<string, string | number>): string {
  let s = dicts[lang][key] ?? key;
  if (params) for (const k in params) s = s.replace(`{${k}}`, String(params[k]));
  return s;
}

export function tItem(id: string): string {
  return t(`item_${id}` as TKey);
}
